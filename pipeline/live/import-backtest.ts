/**
 * Import a backtest report (reports/*.json) as labeled backtest tips so the
 * leaderboard can show "Backtest" history separately from live results.
 * Usage: tsx pipeline/live/import-backtest.ts reports/backtest-2526-open-w0.8.json
 */
import crypto from "node:crypto";
import fs from "node:fs";
import { closeDb, db, schema } from "./db";
import { LEAGUES } from "../data/football-data";
import type { TipRecord } from "../backtest/run";
import { tipHash } from "./publish";

export async function importBacktest(file: string) {
  const report = JSON.parse(fs.readFileSync(file, "utf8")) as { params: { season: string }; tips: TipRecord[] };
  const rooms = await db.select().from(schema.rooms);
  const roomId = new Map(rooms.map((r) => [r.slug, r.id]));
  let n = 0;
  for (const t of report.tips) {
    const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    const fixtureId = `bt-${t.league}-${t.date}-${slug(t.home)}-${slug(t.away)}`;
    await db
      .insert(schema.fixtures)
      .values({
        id: fixtureId,
        apiFootballId: null,
        leagueCode: t.league,
        leagueName: LEAGUES[t.league].name,
        season: report.params.season,
        home: t.home,
        away: t.away,
        kickoffAt: new Date(`${t.date}T15:00:00Z`),
        status: "finished",
      })
      .onConflictDoNothing();
    const publishedAt = new Date(`${t.date}T08:00:00Z`);
    const res = await db
      .insert(schema.tips)
      .values({
        id: crypto.randomUUID(),
        roomId: roomId.get(t.room)!,
        fixtureId,
        market: t.market,
        selection: t.selection,
        basis: "model",
        oddsAtPublish: t.odds.toFixed(3),
        modelProb: t.modelProb.toFixed(4),
        rationaleEn: "Backtest pick: generated by replaying the strategy on historical data.",
        rationaleAm: "የኋላ ሙከራ ምርጫ፡ ስትራቴጂውን በታሪካዊ መረጃ ላይ በመድገም የተፈጠረ።",
        publishedAt,
        hash: tipHash({ room: t.room, fixture: fixtureId, market: t.market, selection: t.selection, odds: t.odds, basis: "backtest", publishedAt: publishedAt.toISOString() }),
        result: t.outcome,
        profitUnits: t.profit.toFixed(3),
        settledAt: new Date(`${t.date}T22:00:00Z`),
        isBacktest: true,
      })
      .onConflictDoNothing()
      .returning({ id: schema.tips.id });
    n += res.length;
  }
  console.log(`imported ${n} backtest tips from ${file}`);
}

if (process.argv[1]?.endsWith("import-backtest.ts")) {
  const file = process.argv[2];
  if (!file) throw new Error("usage: tsx pipeline/live/import-backtest.ts <report.json>");
  importBacktest(file).finally(() => closeDb());
}
