const dict = { en, am } as const;
export type DictKey = keyof typeof en;

export async function getLocale(): Promise<Locale> {
  await connection();
  const c = (await cookies()).get("locale")?.value;
  return c === "am" ? "am" : "en";
}

export function t(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = dict[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function pick(locale: Locale, enText: string, amText: string): string {
  return locale === "am" && amText ? amText : enText;
}
